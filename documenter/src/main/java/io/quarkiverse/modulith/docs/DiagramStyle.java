package io.quarkiverse.modulith.docs;

/**
 * The style of the PlantUML diagrams, Spring Modulith's {@code DiagramOptions.DiagramStyle}.
 */
public enum DiagramStyle {

    /**
     * Plain UML component diagrams.
     */
    UML,

    /**
     * C4 component diagrams, using the C4-PlantUML library.
     */
    C4
}
