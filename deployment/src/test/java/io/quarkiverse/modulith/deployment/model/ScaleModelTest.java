package io.quarkiverse.modulith.deployment.model;

import static org.assertj.core.api.Assertions.assertThat;

import java.io.IOException;
import java.util.List;
import java.util.Map;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.zip.ZipEntry;
import java.util.zip.ZipFile;

import org.jboss.shrinkwrap.api.asset.ByteArrayAsset;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.TestReporter;
import org.junit.jupiter.api.extension.RegisterExtension;

import io.quarkiverse.modulith.core.data.ModelCodec;
import io.quarkiverse.modulith.deployment.fixtures.model.scalereport.ScaleReport;
import io.quarkus.builder.Version;
import io.quarkus.maven.dependency.Dependency;
import io.quarkus.test.ProdBuildResults;
import io.quarkus.test.ProdModeTestResults;
import io.quarkus.test.QuarkusProdModeTest;

/**
 * Builds and starts a large application, 2,000 class files in 20 modules generated by
 * {@link ScaleFixture}, as a production jar. On Quarkus 4 a model recorded into startup code broke the class file limits
 * at this size, so the build passing is part of the check. The startup time, the time of the first model queries and
 * the resource sizes are published as report entries.
 */
public class ScaleModelTest {

    @RegisterExtension
    static final QuarkusProdModeTest app = new QuarkusProdModeTest()
            .withApplicationRoot(jar -> {
                ScaleFixture.classes().forEach(
                        (name, bytes) -> jar.add(new ByteArrayAsset(bytes), name.replace('.', '/') + ".class"));
                jar.addClass(ScaleReport.class);
            })
            .setApplicationName("scale")
            .setApplicationVersion("1")
            .overrideConfigKey("quarkus.modulith.base-package", ScaleFixture.ROOT)
            .overrideConfigKey("quarkus.modulith.docs.enabled", "false")
            .setForcedDependencies(List.of(Dependency.of("io.quarkus", "quarkus-vertx-http", Version.getVersion())))
            .setRuntimeProperties(Map.of("quarkus.http.port", "0"))
            .setRun(true);

    @ProdBuildResults
    ProdModeTestResults results;

    @Test
    void answersFromTheModelOfTwentyModules() {
        // act
        String output = app.getStartupConsoleOutput();

        // assert
        assertThat(output).contains("scale modules=20 module=m05 direct=m17,m18 dependencies=7674 interfaces=[spi]"
                + " internal=" + ScaleFixture.ROOT + ".m19.internal.Impl0 queries=");
    }

    @Test
    void keepsTheModelOutOfTheStartupCode(TestReporter reporter) throws IOException {
        // arrange
        String output = app.getStartupConsoleOutput();

        // act
        List<? extends ZipEntry> entries;
        try (ZipFile bytecode = new ZipFile(
                results.getBuildDir().resolve("quarkus-app/quarkus/generated-bytecode.jar").toFile())) {
            entries = bytecode.stream().filter(it -> it.getName().contains("ModelRecordingSteps")
                    || it.getName().equals(ModelCodec.LOCATION)).toList();
        }

        // assert
        assertThat(entries).filteredOn(it -> it.getName().endsWith(".class")).allMatch(it -> it.getSize() < 4096);
        assertThat(entries).extracting(ZipEntry::getName).contains(ModelCodec.LOCATION);
        entries.forEach(it -> reporter.publishEntry(it.getName(), Long.toString(it.getSize())));
        reporter.publishEntry("started in", match(output, "started in ([0-9.]+s)"));
        reporter.publishEntry("first model queries", match(output, "queries=([0-9]+ms)"));
    }

    private static String match(String output, String regex) {
        Matcher matcher = Pattern.compile(regex).matcher(output);
        assertThat(matcher.find()).as(regex).isTrue();
        return matcher.group(1);
    }
}
