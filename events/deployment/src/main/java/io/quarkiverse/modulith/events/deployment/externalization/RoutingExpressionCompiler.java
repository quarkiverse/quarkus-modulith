package io.quarkiverse.modulith.events.deployment.externalization;

import java.lang.reflect.Modifier;
import java.util.ArrayDeque;
import java.util.ArrayList;
import java.util.Deque;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Objects;
import java.util.Optional;
import java.util.Set;
import java.util.function.Predicate;

import org.jboss.jandex.ClassInfo;
import org.jboss.jandex.ClassType;
import org.jboss.jandex.DotName;
import org.jboss.jandex.FieldInfo;
import org.jboss.jandex.IndexView;
import org.jboss.jandex.MethodInfo;
import org.jboss.jandex.PrimitiveType;
import org.jboss.jandex.Type;

import io.quarkiverse.modulith.events.externalization.impl.RoutingExpression;
import io.quarkus.arc.Arc;
import io.quarkus.arc.ArcContainer;
import io.quarkus.arc.InstanceHandle;
import io.quarkus.gizmo.AssignableResultHandle;
import io.quarkus.gizmo.BytecodeCreator;
import io.quarkus.gizmo.CatchBlockCreator;
import io.quarkus.gizmo.ClassCreator;
import io.quarkus.gizmo.ClassOutput;
import io.quarkus.gizmo.FieldDescriptor;
import io.quarkus.gizmo.MethodCreator;
import io.quarkus.gizmo.MethodDescriptor;
import io.quarkus.gizmo.ResultHandle;
import io.quarkus.gizmo.TryBlock;

/**
 * Compiles a parsed routing expression into a class implementing {@link RoutingExpression} for one event type. The
 * generated code calls the accessors and bean methods directly, without reflection. Members are resolved and checked
 * at build time, so a typo fails the build. A {@code null} value in the middle of a chain fails the evaluation with an
 * {@link IllegalStateException} naming the expression and the member, and the handle of a named bean is closed even
 * when the chain fails, so a {@code @Dependent} bean is always destroyed.
 */
final class RoutingExpressionCompiler {

    static final String SUFFIX = "$$ModulithRouting";
    private static final DotName OBJECT = DotName.createSimple(Object.class);
    private static final DotName STRING = DotName.createSimple(String.class);

    private final IndexView index;
    private final Map<String, Type> namedBeans;
    private final ClassOutput output;
    private final Predicate<String> applicationClass;
    private int counter;

    /**
     * @param index an index that also knows the JDK and library classes the expressions reach
     * @param namedBeans the bean types by bean name
     * @param applicationClass whether a class, by name, belongs to the application, whose package-private members
     *        the generated class may use
     */
    RoutingExpressionCompiler(IndexView index, Map<String, Type> namedBeans, ClassOutput output,
            Predicate<String> applicationClass) {
        this.index = index;
        this.namedBeans = namedBeans;
        this.output = output;
        this.applicationClass = applicationClass;
    }

    /**
     * @return the event type a class generated by this compiler is for
     */
    static String eventTypeOf(String generatedClass) {
        return generatedClass.substring(0, generatedClass.lastIndexOf(SUFFIX));
    }

    /**
     * @return the name of the generated class, written to the output only when the expression compiled
     * @throws RoutingExpressionException if a member does not exist or is not accessible
     */
    String compile(ClassInfo eventType, ExpressionTemplate template) {
        String className = eventType.name().toString() + SUFFIX + counter++;
        String packageName = eventType.name().packagePrefix();
        CompilationContext context = new CompilationContext(template.source(), eventType.name().toString(), packageName,
                applicationClass.test(eventType.name().toString()));
        Map<String, byte[]> generated = new LinkedHashMap<>();
        try (ClassCreator creator = ClassCreator.builder().classOutput(generated::put).className(className)
                .interfaces(RoutingExpression.class).build()) {
            MethodCreator method = creator.getMethodCreator("evaluate", String.class, Object.class);
            TypedHandle event = new TypedHandle(method.checkCast(method.getMethodParam(0), className(eventType)),
                    ClassType.create(eventType.name()));
            List<TemplateSegment> segments = template.segments();
            if (segments.size() == 1 && segments.get(0) instanceof ChainSegment chain) {
                method.returnValue(toText(method, evaluate(method, event, chain.chain(), context), null));
            } else {
                ResultHandle builder = method.newInstance(MethodDescriptor.ofConstructor(StringBuilder.class));
                for (TemplateSegment segment : segments) {
                    ResultHandle text = segment instanceof ChainSegment chain
                            ? toText(method, evaluate(method, event, chain.chain(), context), "")
                            : method.load(((LiteralSegment) segment).text());
                    method.invokeVirtualMethod(MethodDescriptor.ofMethod(StringBuilder.class, "append",
                            StringBuilder.class, String.class), builder, text);
                }
                method.returnValue(method.invokeVirtualMethod(
                        MethodDescriptor.ofMethod(StringBuilder.class, "toString", String.class), builder));
            }
        }
        generated.forEach(output::write);
        return className;
    }

    private TypedHandle evaluate(BytecodeCreator code, TypedHandle event, ExpressionChain chain,
            CompilationContext context) {
        if (chain.startsAtEvent()) {
            return members(code, event, event, chain, "event", context);
        }
        Type beanType = Optional.ofNullable(namedBeans.get(chain.beanName()))
                .orElseThrow(() -> context.error("there is no bean named " + chain.beanName()
                        + ", declare one with @Named(\"" + chain.beanName() + "\")"));
        ResultHandle container = code.invokeStaticMethod(
                MethodDescriptor.ofMethod(Arc.class, "container", ArcContainer.class));
        ResultHandle instance = code.invokeInterfaceMethod(
                MethodDescriptor.ofMethod(ArcContainer.class, "instance", InstanceHandle.class, String.class),
                container, code.load(chain.beanName()));
        MethodDescriptor close = MethodDescriptor.ofMethod(InstanceHandle.class, "close", void.class);
        TryBlock body = code.tryBlock();
        ResultHandle bean = body.invokeInterfaceMethod(
                MethodDescriptor.ofMethod(InstanceHandle.class, "get", Object.class), instance);
        TypedHandle start = new TypedHandle(body.checkCast(bean, className(classOf(beanType, context))), beanType);
        TypedHandle value = members(body, event, start, chain, "@" + chain.beanName(), context);
        AssignableResultHandle result = code.createVariable(descriptor(value.type()));
        body.assign(result, value.handle());
        CatchBlockCreator failure = body.addCatch(Throwable.class);
        failure.invokeInterfaceMethod(close, instance);
        failure.throwException(failure.getCaughtException());
        code.invokeInterfaceMethod(close, instance);
        return new TypedHandle(result, value.type());
    }

    /**
     * Accesses the members of the chain one after the other, failing with the expression and the member when one in
     * the middle of the chain is {@code null}.
     */
    private TypedHandle members(BytecodeCreator code, TypedHandle event, TypedHandle start, ExpressionChain chain,
            String root, CompilationContext context) {
        TypedHandle current = start;
        String path = root;
        for (ExpressionMember member : chain.members()) {
            if (!path.equals(root) && current.type().kind() != Type.Kind.PRIMITIVE) {
                code.ifNull(current.handle()).trueBranch().throwException(IllegalStateException.class,
                        context.nullValue(path));
            }
            List<TypedHandle> arguments = new ArrayList<>();
            for (ExpressionChain argument : member.arguments()) {
                arguments.add(evaluate(code, event, argument, context));
            }
            current = access(code, current, member, arguments, context);
            path = path + "." + member.name() + (member.call() ? "()" : "");
        }
        return current;
    }

    private TypedHandle access(BytecodeCreator method, TypedHandle target, ExpressionMember member,
            List<TypedHandle> arguments, CompilationContext context) {
        ClassInfo owner = classOf(target.type(), context);
        context.checkAccessible(owner);
        if (member.call()) {
            MethodInfo found = findMethod(owner, member.name(), arguments)
                    .orElseThrow(() -> context.error(owner.name() + " has no accessible method " + member.name()
                            + " taking " + arguments.size() + " matching argument(s)"));
            return invoke(method, target, owner, found, arguments, context);
        }
        Optional<MethodInfo> accessor = findAccessor(owner, member.name());
        if (accessor.isPresent()) {
            return invoke(method, target, owner, accessor.get(), List.of(), context);
        }
        FieldInfo field = findField(owner, member.name())
                .orElseThrow(() -> context.error(owner.name() + " has no accessible property " + member.name()));
        context.checkAccessible(field.declaringClass(), field.flags(), field.name());
        ResultHandle value = method.readInstanceField(
                FieldDescriptor.of(className(owner), field.name(), descriptor(field.type())), target.handle());
        return new TypedHandle(value, field.type());
    }

    private TypedHandle invoke(BytecodeCreator method, TypedHandle target, ClassInfo owner, MethodInfo found,
            List<TypedHandle> arguments, CompilationContext context) {
        context.checkAccessible(found.declaringClass(), found.flags(), found.name() + "()");
        String[] parameters = found.parameterTypes().stream().map(RoutingExpressionCompiler::descriptor)
                .toArray(String[]::new);
        MethodDescriptor descriptor = MethodDescriptor.ofMethod(className(owner), found.name(),
                descriptor(found.returnType()), parameters);
        ResultHandle[] values = arguments.stream().map(TypedHandle::handle).toArray(ResultHandle[]::new);
        ResultHandle result = owner.isInterface()
                ? method.invokeInterfaceMethod(descriptor, target.handle(), values)
                : method.invokeVirtualMethod(descriptor, target.handle(), values);
        return new TypedHandle(result, found.returnType());
    }

    private Optional<MethodInfo> findAccessor(ClassInfo owner, String property) {
        String capitalized = Character.toUpperCase(property.charAt(0)) + property.substring(1);
        return findMethod(owner, "get" + capitalized, List.of())
                .or(() -> findMethod(owner, "is" + capitalized, List.of())
                        .filter(candidate -> isBoolean(candidate.returnType())))
                .or(() -> findMethod(owner, property, List.of()));
    }

    private static boolean isBoolean(Type type) {
        return type.kind() == Type.Kind.PRIMITIVE && type.asPrimitiveType().primitive() == PrimitiveType.Primitive.BOOLEAN;
    }

    /**
     * @return the method taking the arguments, nearest in the hierarchy first, without bridge or other synthetic
     *         methods, the most specific one when overloads accept the arguments
     */
    private Optional<MethodInfo> findMethod(ClassInfo owner, String name, List<TypedHandle> arguments) {
        List<MethodInfo> candidates = hierarchy(owner).stream().flatMap(type -> type.methods().stream())
                .filter(candidate -> candidate.name().equals(name) && !Modifier.isStatic(candidate.flags())
                        && !candidate.isSynthetic() && candidate.parametersCount() == arguments.size()
                        && accepts(candidate, arguments))
                .toList();
        return candidates.stream()
                .filter(candidate -> candidates.stream().allMatch(other -> isMoreSpecific(candidate, other)))
                .findFirst()
                .or(() -> candidates.stream().findFirst());
    }

    private boolean isMoreSpecific(MethodInfo method, MethodInfo other) {
        for (int i = 0; i < method.parametersCount(); i++) {
            if (!isAssignable(method.parameterType(i), other.parameterType(i))) {
                return false;
            }
        }
        return true;
    }

    private boolean accepts(MethodInfo candidate, List<TypedHandle> arguments) {
        for (int i = 0; i < arguments.size(); i++) {
            if (!isAssignable(arguments.get(i).type(), candidate.parameterType(i))) {
                return false;
            }
        }
        return true;
    }

    private Optional<FieldInfo> findField(ClassInfo owner, String name) {
        for (ClassInfo type : hierarchy(owner)) {
            FieldInfo field = type.field(name);
            if (Objects.nonNull(field) && !Modifier.isStatic(field.flags())) {
                return Optional.of(field);
            }
        }
        return Optional.empty();
    }

    boolean isAssignable(Type from, Type to) {
        if (from.kind() == Type.Kind.PRIMITIVE || to.kind() == Type.Kind.PRIMITIVE) {
            return from.equals(to);
        }
        DotName target = erasure(to);
        if (target.equals(OBJECT)) {
            return true;
        }
        ClassInfo type = index.getClassByName(erasure(from));
        return Objects.nonNull(type) && hierarchy(type).stream().anyMatch(candidate -> candidate.name().equals(target));
    }

    /**
     * @return the type, its superclasses and its interfaces, nearest first
     */
    List<ClassInfo> hierarchy(ClassInfo type) {
        List<ClassInfo> result = new ArrayList<>();
        Set<DotName> visited = new HashSet<>();
        Deque<DotName> pending = new ArrayDeque<>(List.of(type.name()));
        while (!pending.isEmpty()) {
            DotName name = pending.poll();
            ClassInfo current = index.getClassByName(name);
            if (visited.add(name) && Objects.nonNull(current)) {
                result.add(current);
                Optional.ofNullable(current.superName()).ifPresent(pending::add);
                pending.addAll(current.interfaceNames());
            }
        }
        return result;
    }

    private ClassInfo classOf(Type type, CompilationContext context) {
        if (type.kind() == Type.Kind.PRIMITIVE || type.kind() == Type.Kind.ARRAY) {
            throw context.error("cannot access members of the " + type + " value");
        }
        return Optional.ofNullable(index.getClassByName(erasure(type)))
                .orElseThrow(() -> context.error("the type " + erasure(type) + " is not known to the build"));
    }

    private static ResultHandle toText(BytecodeCreator method, TypedHandle value, String nullText) {
        Type type = value.type();
        if (type.kind() == Type.Kind.PRIMITIVE) {
            String primitive = descriptor(type);
            String parameter = primitive.equals("B") || primitive.equals("S") ? "I" : primitive;
            return method.invokeStaticMethod(MethodDescriptor.ofMethod(String.class, "valueOf", String.class, parameter),
                    value.handle());
        }
        if (Objects.isNull(nullText) && erasure(type).equals(STRING)) {
            return value.handle();
        }
        ResultHandle fallback = Objects.isNull(nullText) ? method.loadNull() : method.load(nullText);
        return method.invokeStaticMethod(
                MethodDescriptor.ofMethod(Objects.class, "toString", String.class, Object.class, String.class),
                value.handle(), fallback);
    }

    static DotName erasure(Type type) {
        if (type.kind() == Type.Kind.TYPE_VARIABLE) {
            return erasure(type.asTypeVariable().bounds().get(0));
        }
        return type.kind() == Type.Kind.WILDCARD_TYPE ? OBJECT : type.name();
    }

    static String descriptor(Type type) {
        return switch (type.kind()) {
            case PRIMITIVE -> primitive(type.asPrimitiveType().primitive());
            case VOID -> "V";
            case ARRAY -> "[" + descriptor(type.asArrayType().componentType());
            default -> "L" + erasure(type).toString().replace('.', '/') + ";";
        };
    }

    private static String primitive(PrimitiveType.Primitive primitive) {
        return switch (primitive) {
            case BOOLEAN -> "Z";
            case BYTE -> "B";
            case CHAR -> "C";
            case DOUBLE -> "D";
            case FLOAT -> "F";
            case INT -> "I";
            case LONG -> "J";
            case SHORT -> "S";
        };
    }

    private static String className(ClassInfo type) {
        return type.name().toString();
    }
}
